import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';
import { createHash } from 'node:crypto';
import { execSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import pkg from './package.json' with { type: 'json' };

function buildInfo() {
  let sha = (process.env.GITHUB_SHA ?? '').slice(0, 7);
  if (!sha) {
    try { sha = execSync('git rev-parse --short=7 HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch { sha = 'local'; }
  }
  return { version: pkg.version, sha, built: new Date().toISOString() };
}
const BUILD = buildInfo();

/** Emits sw.js: a cache-first service worker whose precache list is the exact set of files in the build. */
function serviceWorker(): Plugin {
  return {
    name: 'dom-service-worker',
    apply: 'build',
    generateBundle(_o, bundle) {
      // only the Latin font subsets are precached; other scripts are never needed by the game's text
      const files = Object.keys(bundle).filter((f) => !f.endsWith('.map') && !/(cyrillic|greek|vietnamese)/.test(f));
      const pub = ['manifest.webmanifest', 'icons/icon.svg', 'icons/icon-192.png', 'icons/icon-512.png', 'icons/maskable-512.png', 'icons/apple-touch-icon.png'].filter((f) => existsSync(`public/${f}`));
      const all = ['./', ...files.filter((f) => f !== 'index.html'), 'index.html', ...pub];
      const hash = createHash('sha256');
      for (const f of files) {
        const it = bundle[f];
        hash.update(f).update(it.type === 'chunk' ? it.code : typeof it.source === 'string' ? it.source : Buffer.from(it.source));
      }
      for (const m of ['public/music/manifest.json', 'public/backdrops/manifest.json']) if (existsSync(m)) hash.update(readFileSync(m));   // new tracks and rooms must not be served stale
      const version = hash.digest('hex').slice(0, 12);
      this.emitFile({ type: 'asset', fileName: 'version.json', source: JSON.stringify({ ...BUILD, cache: `dom-${version}` }) });
      const source = `// generated by vite.config.ts
const CACHE = 'dom-${version}';
const PRECACHE = ${JSON.stringify(all)};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE))); });
self.addEventListener('message', (e) => { if (e.data === 'skipWaiting') self.skipWaiting(); });
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('dom-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request; const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin || url.pathname.endsWith('/version.json')) return;
  e.respondWith(caches.open(CACHE).then((c) => c.match(req, { ignoreSearch: true })).then((hit) => hit || fetch(req).then((res) => {
    if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
    return res;
  }).catch(() => caches.open(CACHE).then((c) => c.match('./')))));
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source });
    },
  };
}

export default defineConfig({
  base: './',
  plugins: [react(), serviceWorker()],
  define: { __BUILD__: JSON.stringify(BUILD) },
  server: { port: 8140, strictPort: true },
  preview: { port: 8141, strictPort: true },
  build: { target: 'es2022', assetsInlineLimit: 0, chunkSizeWarningLimit: 2000 },
  test: { include: ['tests/**/*.test.ts'], testTimeout: 180000, pool: 'forks' },
});
